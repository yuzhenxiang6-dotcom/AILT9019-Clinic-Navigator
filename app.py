"""
app.py - Minimal Streamlit front end for the UHS retrieval QA demo.

Design constraints for live recording:
  * One input box, one Search button, nothing else to configure.
  * No settings panel, no sidebar controls, nothing that can be mis-clicked.
  * Status is shown as a single banner so the viewer always knows which mode
    produced the answer on screen.
"""

from __future__ import annotations

import sys
from html import escape
from pathlib import Path

import streamlit as st

PROJECT_ROOT = Path(__file__).resolve().parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from query import get_answer  # noqa: E402

st.set_page_config(
    page_title="UHS Retrieval QA",
    page_icon="*",
    layout="centered",
)

# --- Styles -----------------------------------------------------------------
st.markdown(
    """
    <style>
        .block-container { max-width: 1000px; padding-top: 2rem; }
        .mode-banner {
            padding: 0.6rem 1rem; border-radius: 0.4rem;
            font-weight: 600; font-size: 0.95rem; margin-bottom: 0.8rem;
        }
        .mode-online  { background: #e6f4ea; color: #137333; border-left: 4px solid #137333; }
        .mode-offline { background: #fef7e0; color: #8a6100; border-left: 4px solid #f9ab00; }
        .mode-blocked { background: #fce8e6; color: #c5221f; border-left: 4px solid #c5221f; }
        .mode-empty   { background: #f1f3f4; color: #5f6368; border-left: 4px solid #5f6368; }
        .reason-box {
            background: #f1f3f4; color: #5f6368; font-size: 0.8rem;
            padding: 0.5rem 0.8rem; border-radius: 0.3rem; margin: 0.5rem 0 1rem 0;
            font-family: monospace;
        }
        .citation-card {
            border: 1px solid #dadce0; border-left: 4px solid #1a73e8;
            border-radius: 0.3rem; padding: 0.8rem; margin-bottom: 0.8rem;
            background: #ffffff;
        }
        .citation-title { font-weight: 700; font-size: 0.9rem; margin-bottom: 0.3rem; }
        .citation-text  { font-size: 0.85rem; color: #3c4043; margin: 0.4rem 0; }
        .citation-url   { font-size: 0.78rem; color: #1a73e8; word-break: break-all; }
        .citation-score { font-size: 0.75rem; color: #80868b; font-family: monospace; }
    </style>
    """,
    unsafe_allow_html=True,
)

# --- Header -----------------------------------------------------------------
st.title("UHS Retrieval QA")
st.caption("BM25 retrieval over local HTML passages, with LLM synthesis and citations.")
st.warning("Informational prototype: no diagnosis, treatment advice, emergency assessment or booking actions. Contact official emergency services for urgent help.")
st.caption("Static source snapshot from the supplied project archive. Live clinic availability, holidays and temporary closures are not verified. Do not enter personal health information.")

# --- Input ------------------------------------------------------------------
with st.form("search_form", clear_on_submit=False):
    query = st.text_input(
        "Question",
        placeholder="e.g. What are the opening hours of the UHS main clinic?",
        label_visibility="collapsed",
    )
    submitted = st.form_submit_button("Search", type="primary")

# --- Results ----------------------------------------------------------------
if submitted:
    with st.spinner("Searching..."):
        result = get_answer(query)

    mode = result["mode"]

    if mode == "online":
        banner = '<div class="mode-banner mode-online">Online Mode - answer generated by the model</div>'
    elif mode == "offline":
        banner = '<div class="mode-banner mode-offline">API not connected - switched to offline mode. Showing retrieved source text.</div>'
    elif mode == "blocked":
        banner = '<div class="mode-banner mode-blocked">Query blocked - outside the scope of this system.</div>'
    else:
        banner = '<div class="mode-banner mode-empty">No result</div>'

    st.markdown(banner, unsafe_allow_html=True)

    # Always show the real reason. Distinguishes "no key" (expected) from
    # "wrong model name" (silent failure) -- see query.py.
    if result["reason"] and mode in ("offline", "blocked"):
        st.markdown(
            f'<div class="reason-box">{escape(result["reason"])}</div>',
            unsafe_allow_html=True,
        )

    answer_col, cite_col = st.columns([3, 2])

    with answer_col:
        st.subheader("Answer")
        st.markdown(result["answer"])

    with cite_col:
        st.subheader("Citations")
        citations = result["citations"]

        if not citations:
            st.info("No citations for this query.")
        else:
            for i, passage in enumerate(citations, start=1):
                url = passage.get("url", "")
                score = passage.get("score")
                score_text = f"BM25 score: {score:.2f}" if isinstance(score, (int, float)) else ""

                st.markdown(
                    f"""
                    <div class="citation-card">
                        <div class="citation-title">S{i} &middot; {passage.get('source_id', '?')}</div>
                        <div class="citation-text">{escape(str(passage.get('text', ''))[:300])}</div>
                        <div class="citation-url">{escape(str(url))}</div>
                        <div class="citation-score">{score_text}</div>
                    </div>
                    """,
                    unsafe_allow_html=True,
                )

    st.divider()
    st.caption(
        "Retrieval: BM25 (top 3) &middot; "
        "Generation: Alibaba Cloud Bailian (OpenAI-compatible) &middot; "
        "Fallback: offline retrieval on any API failure"
    )

else:
    st.info(
        "Enter a question above and press **Search**. "
        "Citations identify the highest-ranked source passages."
    )